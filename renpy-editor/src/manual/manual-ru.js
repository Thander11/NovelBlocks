<section id="patch">
  <h2>Патчи</h2>
  <p>Некоторые новеллы выходят в магазинах вроде Steam без части контента, а автор выкладывает этот контент на своём сайте как <strong>патч</strong>, который игроки добавляют в игру. Редактор всё подготовит.</p>
  <h3>1. Включить патч</h3>
  <p>В разделе <strong>{{game_settings}} → {{patch}}</strong> включи «{{patch_enable}}», дай патчу название и напиши инструкцию для игроков (она войдёт в патч как текстовый файл). Справа видно, что входит в патч и возможные проблемы.</p>
  <h3>2. Отметить контент патча</h3>
  <ul>
    <li><strong>Блок «{{block_patch}}»</strong> (группа «{{block_group_patch}}» в палитре). У него две части:
      <ul>
        <li><strong>{{patch_with}}:</strong> блоки, которые видят только игроки с патчем. Они хранятся отдельно, в <code>game/patch/</code>.</li>
        <li><strong>{{patch_without}}:</strong> то, что видят игроки без патча (например, в Steam). Можно оставить пустым: тогда история просто продолжится.</li>
      </ul>
      Чтобы сохранить контент патча, у сцены должен быть выбран «{{target_label}}».</li>
    <li><strong>Изображения:</strong> через <em>{{patch_choose_images}}</em> отмечаются изображения, которые идут только в патч. Редактор переносит их в <code>images/patch/</code> вместе с объявлением. Если снять отметку, они вернутся в игру.</li>
  </ul>
  <p>В предпросмотре сцены появляется переключатель <strong>{{patch_without}} / {{patch_with}}</strong>, чтобы видеть обе версии, а на карте сцены с контентом патча помечены.</p>
  <h3>3. Сборка</h3>
  <p>В окне <strong>{{build_game}}</strong> выбирается:</p>
  <ul>
    <li><strong>{{build_patch_split}}:</strong> для Steam. Игра выходит без контента патча (даже в заблокированном виде), а патч — отдельным .zip, с упакованным контентом без читаемого кода и с инструкцией.</li>
    <li><strong>{{build_patch_full}}:</strong> всё в одной игре — для твоего сайта или itch.io.</li>
    <li><strong>{{build_patch_base}}:</strong> чтобы загрузить обновление, когда патч не менялся.</li>
  </ul>
  <p>Перед сборкой редактор проверяет, что ничто в игре не зависит от патча: например, изображение из патча, которое используется и в обычной сцене, или переход к сцене, которая есть только в патче.</p>
  <h3>Для игроков</h3>
  <p>Установка патча — это распаковка .zip в папку игры (где лежит исполняемый файл). Игра сама его обнаружит. На Mac папка игры находится внутри приложения; если выпускаешь игру для Mac, объясни это в инструкции.</p>
  <div class="man-note"><strong>Правила магазинов:</strong> перед публикацией в Steam или другом магазине проверь его правила о контенте, добавляемом вне магазина.</div>
</section>

